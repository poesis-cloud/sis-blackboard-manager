package cloud.poesis.sie.bbman.entity;

import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.Objects;
import java.util.UUID;

import cloud.poesis.sie.bbman.type.BlackboardStatus;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.Id;
import jakarta.persistence.OneToMany;
import jakarta.persistence.OrderBy;
import jakarta.persistence.Table;

/**
 * Top-level resource of the substrate.
 *
 * <p>
 * Maps to the {@code blackboard} table. The {@code id} is generated by the
 * column default
 * {@code uuid_v7()} (DB-side). {@code timestamp} is DB-assigned.
 *
 * <p>
 * {@code status} is updated through
 * {@link cloud.poesis.sie.bbman.service.BlackboardService}'s
 * FSM enforcement; it is exposed through the entity but not directly settable
 * from outside the
 * service layer.
 *
 * @author Clément Cazaud
 * @since 1.0.0
 */
@Entity
@Table(name = "blackboard")
public class BlackboardEntity {

  @Id
  @GeneratedValue
  @Column(name = "id", nullable = false, updatable = false, insertable = false)
  private UUID id;

  @Column(name = "name", nullable = false, updatable = false)
  private String name;

  @Column(name = "\"timestamp\"", nullable = false, updatable = false, insertable = false)
  private Instant timestamp;

  @Enumerated(EnumType.STRING)
  @Column(name = "status", nullable = false)
  private BlackboardStatus status;

  @Column(name = "seal_timestamp")
  private Instant sealTimestamp;

  @OneToMany(mappedBy = "blackboard", fetch = FetchType.LAZY)
  @OrderBy("name ASC")
  private List<PanelEntity> panels;

  /** JPA requires a no-arg constructor. */
  protected BlackboardEntity() {
  }

  /**
   * Creates a new Blackboard with the given name in {@code OPEN} status.
   *
   * @param name client-supplied free-form label; must be non-null
   */
  public BlackboardEntity(String name) {
    this.name = Objects.requireNonNull(name, "name");
    this.status = BlackboardStatus.OPEN;
    this.panels = new ArrayList<>();
  }

  public UUID getId() {
    return id;
  }

  public String getName() {
    return name;
  }

  public Instant getTimestamp() {
    return timestamp;
  }

  public BlackboardStatus getStatus() {
    return status;
  }

  /**
   * Updates the Blackboard status. Intended for service-layer FSM transitions
   * only.
   *
   * @param status the new lifecycle status; must be non-null
   */
  public void setStatus(BlackboardStatus status) {
    this.status = Objects.requireNonNull(status, "status");
  }

  public Instant getSealTimestamp() {
    return sealTimestamp;
  }

  /**
   * Sets the seal timestamp on the {@code OPEN -> SEALED} or
   * {@code SEALING -> SEALED} transition.
   *
   * @param sealTimestamp the seal moment; may be {@code null} until the seal
   *                      transition
   */
  public void setSealTimestamp(Instant sealTimestamp) {
    this.sealTimestamp = sealTimestamp;
  }

  public List<PanelEntity> getPanels() {
    return panels;
  }

  @Override
  public boolean equals(Object o) {
    if (this == o)
      return true;
    if (o == null || getClass() != o.getClass())
      return false;
    BlackboardEntity that = (BlackboardEntity) o;
    return id != null && Objects.equals(id, that.id);
  }

  @Override
  public int hashCode() {
    return getClass().hashCode();
  }
}
